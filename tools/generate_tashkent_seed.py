#!/usr/bin/env python3
"""Regenerate Tashkent-only location seed data for the product module.

Reads the curated hierarchy (city -> districts -> massivs -> quarters) produced
by the geo sweep and emits the JSON files consumed by
product/.../config/DatabaseSeeder plus the admin map-center constant.

Usage:
    python3 tools/generate_tashkent_seed.py /path/to/tashkent_quarters.json
"""
import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
DATA = REPO / "product" / "src" / "main" / "resources" / "data"
ADMIN_CONST = REPO.parents[1] / "sim-sim-admin" / "src" / "app" / "shared" / "constants" / "district-centers.ts"

REGION_ID = 1
REGION = {"id": REGION_ID, "name_uz": "Toshkent", "name_oz": "Тошкент", "name_ru": "Ташкент"}

# OSM admin-boundary centroids (lon, lat) keyed by district name_uz.
DISTRICT_CENTERS = {
    "Bektemir tumani": (69.3348, 41.2284),
    "Chilonzor tumani": (69.2044, 41.2673),
    "Mirobod tumani": (69.2953, 41.2749),
    "Mirzo Ulug'bek tumani": (69.3751, 41.3643),
    "Olmazor tumani": (69.2173, 41.3601),
    "Sergeli tumani": (69.2581, 41.2321),
    "Shayxontohur tumani": (69.2174, 41.3248),
    "Uchtepa tumani": (69.1599, 41.2962),
    "Yunusobod tumani": (69.2860, 41.3540),
    "Yashnobod tumani": (69.3790, 41.2936),
    "Yangihayot tumani": (69.2407, 41.2021),
}


def write_json(path: Path, rows: list[dict]) -> None:
    lines = ["["]
    for i, row in enumerate(rows):
        sep = "," if i < len(rows) - 1 else ""
        lines.append(json.dumps(row, ensure_ascii=False) + sep)
    lines[-1] = lines[-1] + "]" if len(rows) else "]"
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> None:
    if len(sys.argv) != 2:
        sys.exit("usage: generate_tashkent_seed.py <tashkent_quarters.json>")
    src = json.loads(Path(sys.argv[1]).read_text(encoding="utf-8"))

    districts: list[dict] = []
    villages: list[dict] = []
    village_id = 1
    district_id = 1
    uz_fallback: list[str] = []
    dropped: list[str] = []

    for d in src["districts"]:
        named_massivs = [m for m in d["massivs"] if m["name_ru"]]
        multi = len(named_massivs) > 1
        districts.append({
            "id": district_id,
            "region_id": REGION_ID,
            "name_uz": d["name_uz"],
            "name_oz": d["name_uz"],
            "name_ru": d["name_ru"],
        })

        seen_ru: set[str] = set()
        seen_uz: set[str] = set()
        for m in d["massivs"]:
            for q in sorted(m["quarters"], key=lambda x: x["seq"]):
                if multi and m["name_ru"]:
                    name_ru = f"{m['name_ru']}, {q['name_ru']}"
                    name_uz = f"{m['name_uz']} {q['name_uz']}" if m["name_uz"] else q["name_uz"]
                else:
                    name_ru = q["name_ru"]
                    name_uz = q["name_uz"]
                if not name_uz:
                    name_uz = name_ru
                if name_ru in seen_ru or name_uz in seen_uz:
                    dropped.append(f"{d['name_uz']}: {name_ru} / {name_uz}")
                    continue
                if name_uz == name_ru:
                    uz_fallback.append(f"{d['name_uz']}: {name_ru}")
                seen_ru.add(name_ru)
                seen_uz.add(name_uz)
                villages.append({
                    "id": village_id,
                    "district_id": district_id,
                    "name_uz": name_uz,
                    "name_oz": name_uz,
                    "name_ru": name_ru,
                })
                village_id += 1
        district_id += 1

    write_json(DATA / "regions.json", [REGION])
    write_json(DATA / "districts.json", districts)
    write_json(DATA / "villages.json", villages)

    mahallas = DATA / "mahallas.json"
    if mahallas.exists():
        mahallas.unlink()

    missing = [d["name_uz"] for d in districts if d["name_uz"] not in DISTRICT_CENTERS]
    if missing:
        sys.exit(f"missing OSM centroid for districts: {missing}")
    body = ",\n".join(
        f"  {d['id']}: {{ lon: {DISTRICT_CENTERS[d['name_uz']][0]}, lat: {DISTRICT_CENTERS[d['name_uz']][1]} }}"
        for d in districts
    )
    ADMIN_CONST.write_text(
        "// Generated by new-backend/simsim/tools/generate_tashkent_seed.py - do not edit.\n"
        "// Map center (lon/lat) per district id, used to pan the admin publish-form map.\n"
        "export const DISTRICT_CENTERS: Record<number, { lon: number; lat: number }> = {\n"
        + body
        + "\n};\n",
        encoding="utf-8",
    )

    print(f"regions={1} districts={len(districts)} villages={len(villages)}")
    if dropped:
        print(f"duplicate quarters skipped ({len(dropped)}):")
        for line in dropped:
            print("  " + line)
    if uz_fallback:
        print(f"uz fallback to ru ({len(uz_fallback)}):")
        for line in uz_fallback:
            print("  " + line)


if __name__ == "__main__":
    main()
