package net.jemsit.notify;

import jakarta.annotation.PostConstruct;
import lombok.extern.slf4j.Slf4j;
import org.springframework.dao.DuplicateKeyException;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.core.RowMapper;
import org.springframework.jdbc.support.GeneratedKeyHolder;
import org.springframework.jdbc.support.KeyHolder;

import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.time.Instant;
import java.util.List;

/**
 * All persistence for the module, as plain SQL over a {@link JdbcTemplate}.
 *
 * <p><b>Why this is not JPA.</b> The obvious implementation is an {@code @Entity} plus a
 * {@code JpaRepository}, and it fails on the very project this module was written for. SimSim's
 * application class declares:
 *
 * <pre>{@code
 * @ComponentScan(basePackages = {"net.jemsit"})
 * @EntityScan(basePackages = {"net.jemsit"})
 * @EnableJpaRepositories(basePackages = {"net.jemsit"})
 * }</pre>
 *
 * This module lives in {@code net.jemsit.notify}, which is inside all three of those. So SimSim would
 * already register the module's repositories, and the module declaring its own
 * {@code @EnableJpaRepositories} to support hosts with a narrower scan would register them a second
 * time - two definitions under the same bean name, which Boot rejects outright because it disables
 * bean definition overriding. A module that only installs into projects whose package layout happens
 * to suit it is not portable, which is the single requirement here.
 *
 * <p>{@code JdbcTemplate} needs no scanning of any kind: no entities to find, no repositories to
 * register, no {@code LocalContainerEntityManagerFactoryBean} to agree with. It also widens what counts
 * as a host - any Spring Boot application with a {@code DataSource} can install this, including ones
 * that never adopted JPA. The cost is hand-written SQL and hand-written DDL, both of which are short
 * and both of which are in this one file rather than spread across annotations.
 *
 * <p>Timestamps are stored as epoch milliseconds in a {@code BIGINT}. Not because it is prettier than
 * a {@code TIMESTAMP} column but because it is the only choice that behaves identically on H2 and
 * PostgreSQL without a dialect-specific type, and because the arithmetic this table actually does -
 * {@code expires_at > now} - is a long comparison either way.
 */
@Slf4j
public class NotifyStore {

    private static final String CREATE_OUTBOX = """
            create table if not exists notify_outbox (
                id          bigint generated by default as identity primary key,
                title       varchar(200) not null,
                body        varchar(2000),
                tag         varchar(64),
                priority    varchar(16),
                source      varchar(64),
                created_at  bigint not null,
                expires_at  bigint not null
            )""";

    private static final String CREATE_OUTBOX_INDEX =
            "create index if not exists ix_notify_outbox_created_at on notify_outbox (created_at)";

    /**
     * The column is {@code cursor_pos}, not {@code cursor}: {@code CURSOR} is a reserved word in
     * several dialects and quoting it would mean dialect-specific quoting rules.
     */
    private static final String CREATE_DEVICE = """
            create table if not exists notify_device (
                device_id     varchar(64) primary key,
                label         varchar(120),
                cursor_pos    bigint not null,
                registered_at bigint not null,
                last_seen_at  bigint not null
            )""";

    private static final String INSERT_OUTBOX = """
            insert into notify_outbox (title, body, tag, priority, source, created_at, expires_at)
            values (?, ?, ?, ?, ?, ?, ?)""";

    /**
     * The replay query, and the whole reason the stream survives a dead socket.
     *
     * <p>Expiry is a predicate here rather than a rewrite job, which keeps two things true at once: an
     * expired row stops being replayable the instant it expires, and the row itself is still on disk
     * for the retention sweep to remove on its own schedule. There is no window where a notification is
     * deleted but still replayable, or replayable but already deleted.
     *
     * <p>{@code order by id asc} is not decoration. A device applies these in order and reports the
     * highest id it reached, so delivering them out of order would let its cursor claim coverage of
     * rows it never saw.
     */
    private static final String SELECT_REPLAYABLE = """
            select id, title, body, tag, priority, source, created_at
            from notify_outbox
            where id > ? and expires_at > ?
            order by id asc
            limit ?""";

    private static final String SELECT_MAX_ID = "select max(id) from notify_outbox";
    private static final String COUNT_REPLAYABLE = "select count(*) from notify_outbox where expires_at > ?";
    private static final String DELETE_EXPIRED = "delete from notify_outbox where created_at < ?";

    private static final String SELECT_DEVICE =
            "select device_id, label, cursor_pos, registered_at, last_seen_at from notify_device where device_id = ?";
    private static final String SELECT_DEVICES =
            "select device_id, label, cursor_pos, registered_at, last_seen_at from notify_device order by last_seen_at desc";
    private static final String INSERT_DEVICE =
            "insert into notify_device (device_id, label, cursor_pos, registered_at, last_seen_at) values (?, ?, ?, ?, ?)";
    private static final String UPDATE_DEVICE =
            "update notify_device set label = ?, cursor_pos = ?, last_seen_at = ? where device_id = ?";
    private static final String COUNT_DEVICES = "select count(*) from notify_device";

    private static final RowMapper<NotifyMessage> MESSAGE_MAPPER = (ResultSet rs, int row) -> new NotifyMessage(
            rs.getLong("id"),
            rs.getString("title"),
            rs.getString("body"),
            rs.getString("tag"),
            rs.getString("priority"),
            rs.getString("source"),
            Instant.ofEpochMilli(rs.getLong("created_at")));

    private final JdbcTemplate jdbc;
    private final NotifyProperties properties;

    public NotifyStore(JdbcTemplate jdbc, NotifyProperties properties) {
        this.jdbc = jdbc;
        this.properties = properties;
    }

    /**
     * Creates the two tables if they are missing.
     *
     * <p>Idempotent and additive: it never alters an existing table and never touches one it did not
     * create. Set {@code notify.create-schema=false} on any host that manages its own schema through
     * Flyway or Liquibase and apply {@code notify-schema.sql} from this module's resources instead -
     * the DDL is duplicated there deliberately, so a host under migration control has a file to review
     * rather than a statement to reverse-engineer out of a Java class.
     *
     * <p>A failure here is logged and rethrown rather than swallowed. Every other database error in
     * this class degrades gracefully because a lost bookkeeping write costs nothing; this one cannot,
     * because the outbox <em>is</em> the delivery mechanism and a module that silently cannot persist
     * is a module that silently drops everything.
     */
    @PostConstruct
    void createSchema() {
        if (!properties.isCreateSchema()) {
            log.info("notify.create-schema is false - assuming notify_outbox and notify_device exist");
            return;
        }
        jdbc.execute(CREATE_OUTBOX);
        jdbc.execute(CREATE_OUTBOX_INDEX);
        jdbc.execute(CREATE_DEVICE);
        log.info("notify schema ready (notify_outbox, notify_device)");
    }

    /** Commits one notification and returns the id the database assigned, which becomes its cursor. */
    long insert(String title, String body, String tag, String priority, String source,
                Instant createdAt, Instant expiresAt) {
        KeyHolder keys = new GeneratedKeyHolder();
        jdbc.update(connection -> {
            // The key column is named explicitly rather than asking for RETURN_GENERATED_KEYS. The
            // PostgreSQL driver implements that flag by appending "returning *", so the key holder
            // receives every column of the row and getKey() then refuses to choose between them.
            // Naming the column makes it "returning id", which is also all H2, MySQL and SQL Server
            // need - and this module is dropped into hosts on whichever database they already run.
            PreparedStatement statement =
                    connection.prepareStatement(INSERT_OUTBOX, new String[]{"id"});
            statement.setString(1, title);
            statement.setString(2, body);
            statement.setString(3, tag);
            statement.setString(4, priority);
            statement.setString(5, source);
            statement.setLong(6, createdAt.toEpochMilli());
            statement.setLong(7, expiresAt.toEpochMilli());
            return statement;
        }, keys);
        Number key = keys.getKey();
        if (key == null) {
            // Only reachable if the driver ignored the request for generated keys. Without the id there
            // is no cursor to hand the phone, and a notification nobody can acknowledge is one that will
            // be replayed forever - so this is a hard failure, not a warning.
            throw new IllegalStateException("notify insert produced no generated id;"
                    + " the JDBC driver must support returning generated keys");
        }
        return key.longValue();
    }

    List<NotifyMessage> findReplayable(long cursor, Instant now, int limit) {
        return jdbc.query(SELECT_REPLAYABLE, MESSAGE_MAPPER, cursor, now.toEpochMilli(), limit);
    }

    /** Highest id in the outbox, or 0 when it is empty. */
    long findMaxId() {
        Long max = jdbc.queryForObject(SELECT_MAX_ID, Long.class);
        return max == null ? 0L : max;
    }

    long countReplayable(Instant now) {
        Long count = jdbc.queryForObject(COUNT_REPLAYABLE, Long.class, now.toEpochMilli());
        return count == null ? 0L : count;
    }

    int deleteOlderThan(Instant cutoff) {
        return jdbc.update(DELETE_EXPIRED, cutoff.toEpochMilli());
    }

    /**
     * Reads the cursor the server remembers for a device, registering it if this is the first contact
     * and stamping {@code lastSeenAt} either way.
     */
    long readCursor(String deviceId, String label) {
        DeviceRow existing = findDevice(deviceId);
        long now = System.currentTimeMillis();
        if (existing == null) {
            try {
                jdbc.update(INSERT_DEVICE, deviceId, label, 0L, now, now);
            } catch (DuplicateKeyException e) {
                // Two streams for the same device id opened at once, which happens whenever a client
                // reconnects before its previous socket has been noticed as dead. Whoever lost the race
                // just reads the winner's row; the device is registered either way.
                return readCursorOfExisting(deviceId, label, now);
            }
            return 0L;
        }
        jdbc.update(UPDATE_DEVICE, coalesceLabel(label, existing.label()), existing.cursor(), now, deviceId);
        return existing.cursor();
    }

    /**
     * Stores a cursor, monotonically.
     *
     * <p>{@code max(existing, incoming)} rather than a plain write, because acknowledgements arrive
     * over a network that reorders and duplicates. A late ack for 4100 landing after 4200 must not
     * rewind the device: doing so would replay a hundred notifications the phone has already rendered,
     * and it would render every one of them again.
     */
    long writeCursor(String deviceId, String label, long cursor) {
        DeviceRow existing = findDevice(deviceId);
        long now = System.currentTimeMillis();
        if (existing == null) {
            try {
                jdbc.update(INSERT_DEVICE, deviceId, label, cursor, now, now);
                return cursor;
            } catch (DuplicateKeyException e) {
                existing = findDevice(deviceId);
                if (existing == null) {
                    return cursor;
                }
            }
        }
        long next = Math.max(existing.cursor(), cursor);
        jdbc.update(UPDATE_DEVICE, coalesceLabel(label, existing.label()), next, now, deviceId);
        return next;
    }

    long deviceCount() {
        Long count = jdbc.queryForObject(COUNT_DEVICES, Long.class);
        return count == null ? 0L : count;
    }

    List<DeviceRow> devices() {
        return jdbc.query(SELECT_DEVICES, (ResultSet rs, int row) -> new DeviceRow(
                rs.getString("device_id"),
                rs.getString("label"),
                rs.getLong("cursor_pos"),
                Instant.ofEpochMilli(rs.getLong("registered_at")),
                Instant.ofEpochMilli(rs.getLong("last_seen_at"))));
    }

    private long readCursorOfExisting(String deviceId, String label, long now) {
        DeviceRow row = findDevice(deviceId);
        if (row == null) {
            return 0L;
        }
        jdbc.update(UPDATE_DEVICE, coalesceLabel(label, row.label()), row.cursor(), now, deviceId);
        return row.cursor();
    }

    private DeviceRow findDevice(String deviceId) {
        List<DeviceRow> found = jdbc.query(SELECT_DEVICE, (ResultSet rs, int row) -> new DeviceRow(
                rs.getString("device_id"),
                rs.getString("label"),
                rs.getLong("cursor_pos"),
                Instant.ofEpochMilli(rs.getLong("registered_at")),
                Instant.ofEpochMilli(rs.getLong("last_seen_at"))), deviceId);
        return found.isEmpty() ? null : found.get(0);
    }

    /** Keeps an existing label when the caller did not supply one, so a reconnect without a label does
     *  not blank out the name someone bothered to set. */
    private String coalesceLabel(String presented, String existing) {
        if (presented != null && !presented.isBlank()) {
            return presented.trim();
        }
        return existing;
    }

    /** A row of {@code notify_device}, with the connection flag deliberately absent - see the class
     *  comment on {@link NotifyStreamRegistry} for why liveness is memory and not schema. */
    record DeviceRow(String deviceId, String label, long cursor, Instant registeredAt, Instant lastSeenAt) {
    }
}
