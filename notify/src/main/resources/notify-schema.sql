-- Schema for the net.jemsit:notify module.
--
-- Only needed on a host that sets notify.create-schema=false, which is the right setting for any
-- project whose schema is under Flyway or Liquibase control: an application creating tables behind a
-- migration tool's back is exactly the surprise that tool exists to prevent. Copy this file into the
-- host's migration directory as a versioned migration.
--
-- The same DDL also lives in NotifyStore, duplicated deliberately. A host under migration control
-- should have a .sql file to review and diff, not a text block to dig out of a Java class.
--
-- Tested against H2 2.3 and PostgreSQL 14+. The two constructs that are not universally portable are
-- "generated by default as identity" (MySQL wants AUTO_INCREMENT) and "create index if not exists"
-- (Oracle and SQL Server want a guarded block); timestamps are epoch milliseconds in a bigint
-- precisely so that no TIMESTAMP WITH TIME ZONE dialect difference can arise.

create table if not exists notify_outbox
(
    -- The identity column is the resume cursor, so it must be monotonically increasing and must never
    -- be reused or reordered. A device reconnects saying "I have everything up to 4127" and the replay
    -- is "where id > 4127 order by id"; a UUID primary key would make that query meaningless.
    id         bigint generated by default as identity primary key,
    title      varchar(200)  not null,
    body       varchar(2000),
    -- Coalescing key. The phone derives its Android notification id from this, so two publishes with
    -- the same tag update one card in place instead of stacking two.
    tag        varchar(64),
    -- Exactly two values are meaningful: "high" routes to the phone's heads-up channel, anything else
    -- to the silent one. Unrecognised input is normalised to "normal" on the way in.
    priority   varchar(16),
    -- Which backend produced this, for grouping in the phone's inbox. Defaults to the host's
    -- spring.application.name.
    source     varchar(64),
    created_at bigint        not null,
    -- End of the replay window, fixed at publish time as created_at + notify.max-age-ms. Enforced as a
    -- predicate on the replay query rather than by a rewrite job, so a row stops being replayable the
    -- instant it expires while remaining on disk for the retention sweep to remove on its own schedule.
    expires_at bigint        not null
);

-- Used by the retention sweep, which deletes on age rather than on expiry so that the two windows stay
-- independently configurable.
create index if not exists ix_notify_outbox_created_at on notify_outbox (created_at);

create table if not exists notify_device
(
    -- Supplied by the client, so a natural key rather than a generated one. It identifies a phone for
    -- cursor bookkeeping; it is not a credential, and notify.token is.
    device_id     varchar(64) primary key,
    label         varchar(120),
    -- Named cursor_pos because CURSOR is reserved in several dialects and quoting it would mean
    -- dialect-specific quoting rules. Highest outbox id this device has confirmed handling, always
    -- written as max(existing, incoming) so a late duplicate ack cannot rewind it.
    cursor_pos    bigint      not null,
    registered_at bigint      not null,
    last_seen_at  bigint      not null
);

-- There is deliberately no "connected" column anywhere. Whether a socket is open right now is a fact
-- about one JVM's memory, not about the database; persisting it would only ever hand a reader a stale
-- value after a restart. Liveness is answered from NotifyStreamRegistry.
