package net.jemsit.common.data.enums.secondhand;

/**
 * The sub-section a second-hand ad belongs to. This is the second-hand analogue of a car's body
 * type: a fixed, filterable taxonomy, not the top-level {@code MarketplaceCategory} slug.
 */
public enum SecondHandCategory {
    CLOTHING,
    ELECTRONICS,
    FURNITURE,
    BOOKS,
    SPORTS,
    OTHER,
}
